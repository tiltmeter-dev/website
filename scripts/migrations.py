def as_of(generated_at: str) -> str:
    shown = generated_at[:16].replace("T", " ")
    return f'Status as of <time datetime="{e(generated_at)}">{e(shown)}</time> UTC'


def opened_on(records: list[Record]) -> str:
    """When the pull requests were opened: "on 2026-10-26" or "between ... and ..."."""
    days = sorted(day(r["created_at"]) for r in records if r.get("created_at"))
    if not days:
        return ""
    return f"on {days[0]}" if days[0] == days[-1] else f"between {days[0]} and {days[-1]}"


def since_first(records: list[Record], generated_at: str) -> str:
    """How long after the first pull request opened the snapshot was taken."""
    created = [r["created_at"] for r in records if r.get("created_at")]
    if not created:
        return ""
    parse = lambda stamp: datetime.fromisoformat(stamp.replace("Z", "+00:00"))  # noqa: E731
    days = (parse(generated_at) - parse(min(created))).days
    return f"{'less than a day' if days < 1 else plural(days, 'day', 'days')} after the first one opened"


def tiles(s: dict[str, int]) -> str:
    items = [
        ("", "Pull requests opened", num(s["opened"])),
        ("merged", "Merged", num(s["merged"])),
        ("open", "Open", num(s["open"])),
        ("closed", "Closed without merging", num(s["closed"])),
        ("", "Merged, of those opened", f'{s["merged_percent"]}%' if s["opened"] else "—"),
        ("", "Stars of the repositories", num(s["stars"])),
    ]
    cells = "".join(
        f'\n        <div class="stat{" " + c if c else ""}"><dt>{label}</dt><dd>{value}</dd></div>' for c, label, value in items
    )
    return f'      <dl class="stats">{cells}\n      </dl>\n'


def footnote(s: dict[str, int]) -> str:
    if s["private"]:
        tail = plural(s["private"], "pull request is in a private repository.", "pull requests are in private repositories.")
    else:
        tail = "There are none in this snapshot."
    return (
        '      <p class="footnote">Stars come from GitHub at the time of the snapshot, counted once per repository. '
        "Private repositories are counted but not named: their pull requests add to the counts above, "
        f"while their names, links and stars are left out. {tail}</p>\n"
    )


def badge(record: Record) -> str:
    state = record["state"]
    label = {"merged": "Merged", "open": "Open", "closed": "Closed"}[state]
    note = f' title="Closed without merging on {day(record["closed_at"])}"' if state == "closed" else ""
    return f'<span class="badge {state}"{note}>{label}</span>'


def pr_row(record: Record) -> str:
    if record.get("private"):
        repo, stars, link = '<span class="anon">Private repository</span>', "—", "—"
    else:
        repo = f'<a href="{e(record["repository_url"])}">{e(record["repository"])}</a>'
        stars = num(record["stars"])
        link = f'<a href="{e(record["url"])}">#{record["number"]}</a>'
    return (
        f"\n            <tr><td>{repo}</td><td class=\"num\">{stars}</td><td>{badge(record)}</td>"
        f'<td class="date">{day(record["created_at"])}</td><td class="date">{day(record["merged_at"])}</td>'
        f'<td class="num">{link}</td></tr>'
    )


