def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def update_sitemap(out: Path, keys: list[str], date: str) -> None:
    path = out / "sitemap.xml"
    if not path.exists():
        return
    entries = "".join(
        f"  <url>\n    <loc>{SITE}{loc}</loc>\n    <lastmod>{date}</lastmod>\n  </url>\n"
        for loc in ["/migrations/"] + [f"/migrations/{key}/" for key in keys]
    )
    block = f"  <!-- migrations: written by scripts/migrations.py -->\n{entries}  <!-- /migrations -->\n"
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(r"  <!-- migrations: .*?<!-- /migrations -->\n", re.S)
    if pattern.search(text):
        text = pattern.sub(lambda _: block, text)
    else:
        text = text.replace("</urlset>", block + "</urlset>")
    write(path, text)


def remove_stale(out: Path, keys: list[str]) -> None:
    """Delete pages of providers no longer in the input, if this script wrote them."""
    for folder in (out / "migrations").iterdir():
        page = folder / "index.html"
        if folder.is_dir() and folder.name not in keys and [p.name for p in folder.iterdir()] == ["index.html"]:
            if MARK in page.read_text(encoding="utf-8"):
                shutil.rmtree(folder)


def build(args: argparse.Namespace) -> dict[str, Any]:
    out: Path = args.out.resolve()
    status = out / "migrations" / "status.json"
    providers_in, hidden = load_inputs(args.input or [DEFAULT_INPUT])
    if args.offline:
        try:
            old = json.loads(status.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as error:
            fail(f"--offline needs {status}: {error}")
        generated_at = old["generated_at"]
        providers = {
            key: {k: p[k] for k in ("provider", "title", "source")}
            | {"pull_requests": [hide(r, hidden) for r in p["pull_requests"]]}
            for key, p in old["providers"].items()
        }
    else:
        urls = list(dict.fromkeys(url for p in providers_in.values() for url in p["prs"]))
        found = fetch(urls)
        generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        providers = {
            key: {k: p[k] for k in ("provider", "title", "source")}
            | {"pull_requests": [hide({**found[url], "_id": url}, hidden) for url in p["prs"]]}
            for key, p in providers_in.items()
        }
    everything: list[Record] = []
    for p in providers.values():
        p["pull_requests"].sort(key=by_stars)
        p["stats"] = stats(p["pull_requests"])
        everything += p["pull_requests"]
    snapshot = {
        "generated_at": generated_at,
        "generated_by": "scripts/migrations.py, from the GitHub API",
        "note": (
            "Tiltmeter drafted each change notice from the provider's public documentation. "
            "No provider signed or endorsed them. Private repositories are counted but not named."
        ),
        "totals": stats(everything),
        "providers": {
            key: {k: p[k] for k in ("provider", "title", "source", "stats")}
            | {"pull_requests": [public(r) for r in p["pull_requests"]]}
            for key, p in providers.items()
        },
    }
    write(status, json.dumps(snapshot, indent=2, ensure_ascii=False) + "\n")
    write(out / "migrations" / "index.html", index_page(snapshot))
    for key, p in snapshot["providers"].items():
        write(out / "migrations" / key / "index.html", provider_page(key, p, generated_at))
    remove_stale(out, list(providers))
    update_sitemap(out, list(providers), generated_at[:10])
    return snapshot


