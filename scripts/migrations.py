#!/usr/bin/env python3
"""Build the migration tracker at /migrations/ from the live status of its pull requests.

Usage, from anywhere (paths default to this repository):

    python3 scripts/migrations.py             # fetch every pull request, write snapshot and pages
    python3 scripts/migrations.py --offline   # re-render the pages from the last snapshot

The input, migrations/sources.json, maps a provider key (the page's URL slug) to
{"provider": name, "title": ..., "source": changelog URL, "prs": [pull request URLs]}.
The script asks GitHub for each pull request's state, dates and repository through
`gh api graphql` (no shell), writes migrations/status.json with a UTC timestamp, renders
migrations/index.html and migrations/<key>/index.html, and refreshes the migration
entries of sitemap.xml. Rerun it whenever you want fresh numbers.

A repository that is not public, or whose "owner/name" is in a top-level "hidden" list,
appears as "Private repository": it counts in opened, merged, open and closed, but its
name, links and stars are left out of the pages and of status.json. GitHub Pages publishes
every file in this repository, so keep private pull requests and the hidden list in a
second input outside it; inputs are merged in order:

    python3 scripts/migrations.py --input migrations/sources.json --input ~/private.json

Options: --out DIR writes everything under DIR instead of this repository (for a dry run).
Needs Python 3.10+ and an authenticated GitHub CLI (`gh auth login`).
"""

