# Input


def load_inputs(paths: list[Path]) -> tuple[dict[str, dict[str, Any]], set[str]]:
    """Merge the inputs in order: PR lists add up, the first title, source and name win."""
    providers: dict[str, dict[str, Any]] = {}
    hidden: set[str] = set()
    for path in paths:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as error:
            fail(f"cannot read {path}: {error}")
        if not isinstance(data, dict):
            fail(f"{path} must hold a JSON object")
        for key, entry in data.items():
            if key == "hidden":
                if not isinstance(entry, list) or not all(isinstance(n, str) and REPO.fullmatch(n) for n in entry):
                    fail(f'{path}: "hidden" must be a list of "owner/name" strings')
                hidden.update(name.lower() for name in entry)
                continue
            if not KEY.fullmatch(key) or not isinstance(entry, dict):
                fail(f"{path}: {key!r} must be a lowercase slug mapping to an object")
            merged = providers.setdefault(
                key, {"provider": "", "title": "", "source": "", "prs": [], "adopted": {}, "gone": []}
            )
            for field in ("provider", "title", "source"):
                value = entry.get(field)
                if value is not None and not isinstance(value, str):
                    fail(f"{path}: {key}.{field} must be a string")
                if value and not merged[field]:
                    merged[field] = value.strip()
            prs = entry.get("prs", [])
            if not isinstance(prs, list):
                fail(f"{path}: {key}.prs must be a list")
            for url in prs:
                url = url.rstrip("/") if isinstance(url, str) else url
                if not isinstance(url, str) or not PR_URL.fullmatch(url):
                    fail(f"{path}: {key}.prs has {url!r}, not a GitHub pull request URL")
                if url not in merged["prs"]:
                    merged["prs"].append(url)
            adopted = entry.get("adopted", {})
            if not isinstance(adopted, dict):
                fail(f"{path}: {key}.adopted must map pull request URLs to commit or pull request URLs")
            for url, target in adopted.items():
                pr = PR_URL.fullmatch(url)
                where = (COMMIT_URL.fullmatch(target) or PR_URL.fullmatch(target)) if isinstance(target, str) else None
                if not pr or not where or (pr[1], pr[2]) != (where[1], where[2]) or target == url:
                    fail(f"{path}: {key}.adopted needs a pull request URL and, in the same repository, "
                         "a commit URL or another pull request URL")
                merged["adopted"][url] = target
            gone = entry.get("gone", [])
            if not isinstance(gone, list) or not all(isinstance(u, str) and PR_URL.fullmatch(u) for u in gone):
                fail(f"{path}: {key}.gone must be a list of pull request URLs")
            merged["gone"].extend(u for u in gone if u not in merged["gone"])
    for key, provider in providers.items():
        for field in ("adopted", "gone"):
            stray = set(provider[field]) - set(provider["prs"])
            if stray:
                fail(f"{key}.{field} names pull requests missing from its prs: {', '.join(sorted(stray))}")
        if set(provider["adopted"]) & set(provider["gone"]):
            fail(f"{key}: a pull request cannot be both adopted and gone")
        if not provider["title"]:
            fail(f"{key} has no title")
        if not provider["source"].startswith("https://"):
            fail(f"{key} needs a source that starts with https://")
        provider["provider"] = provider["provider"] or key.capitalize()
    return providers, hidden


# GitHub


QUERY_PART = """
  pr{i}: repository(owner: $o{i}, name: $r{i}) {{
    nameWithOwner url stargazerCount visibility
    pullRequest(number: $n{i}) {{ url number state createdAt mergedAt closedAt }}
  }}"""


def fetch(urls: list[str]) -> dict[str, Record]:
    """Look up each pull request in one GraphQL query per batch, through the gh CLI."""
    found: dict[str, Record] = {}
    missing: list[str] = []
    for start in range(0, len(urls), BATCH):
        chunk = urls[start : start + BATCH]
        params, parts, args = [], [], []
        for i, url in enumerate(chunk):
            owner, name, number = PR_URL.fullmatch(url).groups()  # type: ignore[union-attr]
            params.append(f"$o{i}: String!, $r{i}: String!, $n{i}: Int!")
            parts.append(QUERY_PART.format(i=i))
            args += ["-f", f"o{i}={owner}", "-f", f"r{i}={name}", "-F", f"n{i}={number}"]
        query = f"query({', '.join(params)}) {{{''.join(parts)}\n}}"
        try:
            result = subprocess.run(
                ["gh", "api", "graphql", "-f", f"query={query}", *args],
                capture_output=True, text=True, check=False, timeout=120,
            )
        except FileNotFoundError:
            fail("the GitHub CLI (gh) is not installed")
        except subprocess.TimeoutExpired:
            fail("gh api graphql timed out")
        try:
            data = json.loads(result.stdout or "{}").get("data") or {}
        except json.JSONDecodeError:
            data = {}
        if not data and result.returncode != 0:
            fail(f"gh api graphql failed: {(result.stderr or result.stdout).strip()}")
        for i, url in enumerate(chunk):
            repo = data.get(f"pr{i}") or {}
            pr = repo.get("pullRequest")
            if not pr:
                missing.append(url)
                continue
            found[url] = {
                "url": pr["url"],
                "number": pr["number"],
                "repository": repo["nameWithOwner"],
                "repository_url": repo["url"],
                "stars": repo["stargazerCount"],
                "visibility": repo["visibility"].lower(),
                "state": pr["state"].lower(),
                "created_at": pr["createdAt"],
                "merged_at": pr["mergedAt"],
                "closed_at": pr["closedAt"],
            }
    if missing:
        fail("GitHub returned nothing for:\n  " + "\n  ".join(missing))
    return found


# Privacy and numbers


def requested_repo(record: Record) -> str:
    match = PR_URL.fullmatch(record.get("_id") or record.get("url") or "")
    return f"{match[1]}/{match[2]}".lower() if match else ""


def hide(record: Record, hidden: set[str]) -> Record:
    """Keep only state and dates of a private or hidden repository's pull request."""
    if record.get("gone"):
        return record
    private = (
        record.get("private")
        or record.get("visibility") != "public"
        or record.get("repository", "").lower() in hidden
        or requested_repo(record) in hidden
    )
    if not private:
        return record
    kept = {"private": True, **{k: record.get(k) for k in ("state", "created_at", "merged_at", "closed_at")}}
    return {**kept, "_id": record.get("_id")}


def stats(records: list[Record]) -> dict[str, int]:
    seen: set[str] = set()
    unique: list[Record] = []
    for record in records:
        key = record.get("_id") or record.get("url") or str(id(record))
        if key not in seen:
            seen.add(key)
            unique.append(record)
    stars = {r["repository"].lower(): r["stars"] for r in unique if not r.get("private") and not r.get("gone")}
    opened = len(unique)
    merged = sum(r["state"] == "merged" for r in unique)
    closed = sum(r["state"] == "closed" for r in unique)
    adopted = sum(r["state"] == "closed" and r.get("adoption") == "landed" for r in unique)
    return {
        "opened": opened,
        "merged": merged,
        "open": sum(r["state"] == "open" for r in unique),
        "closed": closed,
        "adopted": adopted,
        "picked_up": sum(r["state"] == "closed" and r.get("adoption") == "pending" for r in unique),
        "closed_not_landed": closed - adopted,
        "landed": merged + adopted,
        "merged_percent": percent(merged, opened),
        "landed_percent": percent(merged + adopted, opened),
        "stars": sum(stars.values()),
        "repositories": len(stars),
        "private": sum(1 for r in unique if r.get("private")),
        "gone": sum(1 for r in unique if r.get("gone")),
    }


def percent(part: int, whole: int) -> int:
    """Round half up, so 1 of 8 shows as 13%, not 12%."""
    return (200 * part + whole) // (2 * whole) if whole else 0


def by_stars(record: Record) -> tuple[int, int, str, int]:
    if record.get("gone"):
        return (2, 0, "", 0)
    if record.get("private"):
        return (1, 0, "", 0)
    return (0, -record["stars"], record["repository"].lower(), record["number"])


def public(record: Record) -> Record:
    return {k: v for k, v in record.items() if not k.startswith("_")}


